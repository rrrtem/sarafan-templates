// Run with the bundled Node runtime; exports and verifies the transition style reference.
const fs = require('fs');
const path = require('path');
const deps=process.env.SARAFAN_NODE_MODULES || '/Users/fixed/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules';
const {chromium}=require(path.join(deps,'playwright'));
const sharp=require(path.join(deps,'sharp'));
(async()=>{
 const root=path.resolve(__dirname,'..');
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+root+'/index.html');
 await page.evaluate(()=>document.fonts.ready);
 await page.locator('[data-filter="general"]').click();
 if(await page.locator('.template-entry:visible').count()!==3)throw Error('General filter count');
 await page.locator('a[href="#transition"]').click();
 await page.waitForSelector('#viewer-cards .transition-card');
 if(await page.locator('#viewer-title').textContent()!=='Переходный пост')throw Error('Title');
 await page.keyboard.press('End');
 if(await page.locator('#download-slide').getAttribute('href')!=='exports/sarafan-transition-06.png')throw Error('Download');
 await page.keyboard.press('Home');
 await page.locator('[data-view="grid"]').click();
 await page.evaluate(()=>document.fonts.ready);
 await page.screenshot({path:path.join(root,'preview/transition-grid.png'),fullPage:true});
 const layout=await page.locator('#viewer-cards .ig-card').evaluateAll(cards=>cards.map(c=>({node:c.dataset.nodeId,images:[...c.querySelectorAll('img')].map(img=>({src:img.getAttribute('src'),loaded:img.complete&&img.naturalWidth>0,w:img.offsetWidth,h:img.offsetHeight})),overflow:[...c.querySelectorAll('p')].filter(p=>p.scrollWidth>p.clientWidth+2).map(p=>p.textContent)})));
 if(layout.some(c=>c.images.some(i=>!i.loaded||i.w<=0||i.h<=0)))throw Error('Unloaded/empty asset');
 if(layout.some(c=>c.overflow.length))throw Error('Text horizontal overflow '+JSON.stringify(layout));
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(root,'preview/transition-mobile.png'),fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
 await page.goto('file://'+root+'/index.html#transition/4');
 await page.waitForSelector('#viewer-cards .transition-card');
 if(await page.locator('#download-slide').getAttribute('href')!=='exports/sarafan-transition-04.png')throw Error('Deep link');
 await page.evaluate(()=>{
 const clone=document.getElementById('reference-transition').content.cloneNode(true);
 document.body.replaceChildren(clone);
 const style=document.createElement('style');style.textContent='body{margin:0;background:white}.card-unit{display:block!important}.card-shell{position:relative!important;width:1080px!important;height:1350px!important;overflow:hidden!important}.ig-card{transform:none!important}.grid-label{display:none}';document.head.append(style);
 });
 await page.setViewportSize({width:1080,height:1350});
 await page.evaluate(()=>document.fonts.ready);
 await page.evaluate(()=>Promise.all([...document.images].map(i=>i.decode())));
 const cards=page.locator('.ig-card');
 for(let i=0;i<6;i++)await cards.nth(i).screenshot({path:path.join(root,`exports/sarafan-transition-${String(i+1).padStart(2,'0')}.png`)});
 await browser.close();
 const tiles=await Promise.all(Array.from({length:6},async(_,i)=>({input:await sharp(path.join(root,`exports/sarafan-transition-${String(i+1).padStart(2,'0')}.png`)).resize(360,450).toBuffer(),left:(i%3)*360,top:Math.floor(i/3)*450})));
 await sharp({create:{width:1080,height:900,channels:3,background:'white'}}).composite(tiles).png().toFile(path.join(root,'preview/transition-contact.png'));
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({verified:'general filter, three entries, six slides, keyboard navigation, downloads, deep link, mobile width, all image assets loaded',cards:layout},null,2));
})().catch(e=>{console.error(e);process.exit(1)});
